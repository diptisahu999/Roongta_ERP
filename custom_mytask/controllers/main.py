# -*- coding: utf-8 -*-
import io
import json
import logging
from datetime import datetime
import pytz
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

from odoo import http, fields
from odoo.http import request

_logger = logging.getLogger(__name__)


class MyTasksReportController(http.Controller):

    @http.route('/custom_mytask/export_excel', type='http', auth='user', csrf=False)
    def export_excel(self, filters=None, **kw):
        """Export tasks matching the dashboard filters to an Excel sheet (.xlsx)."""
        try:
            parsed_filters = {}
            if filters:
                if isinstance(filters, str):
                    parsed_filters = json.loads(filters)
                elif isinstance(filters, dict):
                    parsed_filters = filters

            # Call dashboard data with applied filters under the current user's session
            data = request.env['project.task'].get_my_tasks_dashboard_data(filters=parsed_filters)

            # Extract all task items from the 3-level hierarchy
            all_tasks = []
            for dept in data.get('departments', []):
                for tag in dept.get('tags', []):
                    for proj in tag.get('projects', []):
                        for task in proj.get('tasks', []):
                            all_tasks.append(task)

            # Build openpyxl workbook
            wb = openpyxl.Workbook()
            ws = wb.active
            ws.title = "Tasks Report"

            # Enable gridlines
            ws.views.sheetView[0].showGridLines = True

            # Styles definition
            font_title = Font(name="Calibri", size=16, bold=True, color="FFFFFF")
            fill_title = PatternFill(start_color="1A2B4C", end_color="1A2B4C", fill_type="solid")

            font_meta_label = Font(name="Calibri", size=10, bold=True, color="334155")
            font_meta_val = Font(name="Calibri", size=10, color="0F172A")
            fill_meta = PatternFill(start_color="F1F5F9", end_color="F1F5F9", fill_type="solid")

            font_th = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
            fill_th = PatternFill(start_color="2563EB", end_color="2563EB", fill_type="solid")

            font_data = Font(name="Calibri", size=10, color="1E293B")
            font_data_bold = Font(name="Calibri", size=10, bold=True, color="1E293B")
            fill_row_even = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")
            fill_row_odd = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")

            # Status pill fills
            fill_overdue = PatternFill(start_color="FEE2E2", end_color="FEE2E2", fill_type="solid")
            font_overdue = Font(name="Calibri", size=10, bold=True, color="DC2626")

            fill_done = PatternFill(start_color="DCFCE7", end_color="DCFCE7", fill_type="solid")
            font_done = Font(name="Calibri", size=10, bold=True, color="16A34A")

            fill_high_prio = PatternFill(start_color="FEF3C7", end_color="FEF3C7", fill_type="solid")
            font_high_prio = Font(name="Calibri", size=10, bold=True, color="D97706")

            thin_border_side = Side(border_style="thin", color="CBD5E1")
            border_data = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)
            border_header = Border(left=thin_border_side, right=thin_border_side, top=thin_border_side, bottom=thin_border_side)

            align_center = Alignment(horizontal="center", vertical="center")
            align_left = Alignment(horizontal="left", vertical="center")
            align_right = Alignment(horizontal="right", vertical="center")

            # 1. Main Header Title
            ws.merge_cells("A1:O1")
            title_cell = ws["A1"]
            title_cell.value = "ROONGTA DEVELOPERS — TASKS REPORT"
            title_cell.font = font_title
            title_cell.fill = fill_title
            title_cell.alignment = Alignment(horizontal="center", vertical="center")
            ws.row_dimensions[1].height = 36

            # 2. Metadata Information
            user_tz_name = request.env.user.tz or 'Asia/Kolkata'
            try:
                user_tz = pytz.timezone(user_tz_name)
            except Exception:
                user_tz = pytz.timezone('Asia/Kolkata')
            now_str = datetime.now(user_tz).strftime("%d/%m/%Y %I:%M %p")
            user_name = request.env.user.name or 'User'

            ws.merge_cells("A2:O2")
            meta_cell = ws["A2"]
            meta_cell.value = f"Generated On: {now_str}  |  Generated By: {user_name}  |  Total Filtered Tasks: {len(all_tasks)}"
            meta_cell.font = font_meta_label
            meta_cell.fill = fill_meta
            meta_cell.alignment = Alignment(horizontal="left", vertical="center", indent=1)
            ws.row_dimensions[2].height = 22

            # 3. Active Filters Summary
            status_labels = {
                'uncompleted': 'Uncompleted Tasks',
                'pending': 'Pending',
                'overdue': 'Overdue',
                'mgmt_discussion': 'MGMT Discussion',
                'done': 'Done',
                'all': 'All',
            }
            time_labels = {
                'all': 'All Time',
                'today': 'Due Today',
                'this_week': 'Due This Week',
                'this_month': 'Due This Month',
                'overdue': 'Overdue',
            }
            created_filter_labels = {
                'all': 'All Tasks',
                'assigned_to_self': 'Assigned to Self',
                'assigned_to_others': 'Assigned to Others',
            }

            filter_parts = []
            dept_id = parsed_filters.get('department_id')
            if dept_id and dept_id != 'all':
                dept_rec = request.env['hr.department'].sudo().browse(int(dept_id))
                filter_parts.append(f"Department: {dept_rec.name if dept_rec.exists() else dept_id}")
            else:
                filter_parts.append("Department: All")

            status_val = parsed_filters.get('status', 'uncompleted')
            filter_parts.append(f"Status: {status_labels.get(status_val, status_val)}")

            if parsed_filters.get('high_priority'):
                filter_parts.append("Priority: High Priority Only")

            assignee_val = parsed_filters.get('assignee_id', 'all')
            if assignee_val == 'my_tasks':
                filter_parts.append("Assignee: My Tasks")
            elif assignee_val and assignee_val != 'all':
                u_rec = request.env['res.users'].sudo().browse(int(assignee_val))
                filter_parts.append(f"Assignee: {u_rec.name if u_rec.exists() else assignee_val}")

            time_val = parsed_filters.get('time_filter', 'all')
            if time_val and time_val != 'all':
                filter_parts.append(f"Deadline Filter: {time_labels.get(time_val, time_val)}")

            cf_val = parsed_filters.get('created_filter', 'all')
            if cf_val and cf_val != 'all':
                filter_parts.append(f"Assignment: {created_filter_labels.get(cf_val, cf_val)}")

            create_date_val = parsed_filters.get('create_date')
            if create_date_val:
                try:
                    fmt_d = datetime.strptime(str(create_date_val)[:10], "%Y-%m-%d").strftime("%d %b %Y")
                    filter_parts.append(f"Created Date: {fmt_d}")
                except Exception:
                    filter_parts.append(f"Created Date: {create_date_val}")

            if parsed_filters.get('search_term'):
                filter_parts.append(f"Search: \"{parsed_filters.get('search_term')}\"")

            filter_summary = "Applied Filters: " + " | ".join(filter_parts)
            ws.merge_cells("A3:O3")
            f_cell = ws["A3"]
            f_cell.value = filter_summary
            f_cell.font = font_meta_val
            f_cell.fill = fill_meta
            f_cell.alignment = Alignment(horizontal="left", vertical="center", indent=1)
            ws.row_dimensions[3].height = 20

            # Blank spacing row
            ws.row_dimensions[4].height = 10

            # 4. Table Column Headers (Row 5)
            headers = [
                ("Task ID", 12, align_center),
                ("Task Title", 38, align_left),
                ("Department", 22, align_left),
                ("Tag", 20, align_left),
                ("Project", 28, align_left),
                ("Created On", 20, align_center),
                ("Created By", 22, align_left),
                ("Assignees", 26, align_left),
                ("Progress", 12, align_center),
                ("Days Open", 12, align_center),
                ("Deadline", 16, align_center),
                ("Stage / Status", 22, align_center),
                ("Priority", 16, align_center),
                ("Sub-tasks", 12, align_center),
                ("Overdue", 12, align_center),
            ]

            header_row = 5
            ws.row_dimensions[header_row].height = 26
            for col_idx, (col_name, col_width, alignment) in enumerate(headers, start=1):
                cell = ws.cell(row=header_row, column=col_idx, value=col_name)
                cell.font = font_th
                cell.fill = fill_th
                cell.alignment = alignment
                cell.border = border_header
                col_letter = get_column_letter(col_idx)
                ws.column_dimensions[col_letter].width = col_width

            # 5. Populate Data Rows
            current_row = header_row + 1
            total_progress_sum = 0

            priority_map = {
                3: "Urgent (★★★)",
                2: "High (★★)",
                1: "Medium (★)",
                0: "Normal",
            }

            for idx, t in enumerate(all_tasks):
                row_fill = fill_row_odd if idx % 2 == 1 else fill_row_even
                ws.row_dimensions[current_row].height = 22

                t_id = t.get('id') or ''
                t_name = t.get('name') or ''
                t_dept = t.get('dept_name') or ''
                t_tag = t.get('tag_name') or ''
                t_proj = t.get('project_name') or ''
                t_created_on = t.get('create_date') or ''
                t_created_by = t.get('create_user', {}).get('name') if t.get('create_user') else ''
                t_assignees = ", ".join(a.get('name', '') for a in t.get('assignees', []))
                t_prog = t.get('progress', 0)
                total_progress_sum += t_prog
                t_prog_str = f"{t_prog}%"
                t_days_open = t.get('days_open', 0)
                t_deadline = t.get('due_date') or ''
                t_stage = t.get('stage_name') or t.get('state') or ''
                prio_int = t.get('priority_int', 0)
                t_priority = priority_map.get(prio_int, "Normal")
                t_subtasks = t.get('subtask_count', 0)
                t_is_overdue = t.get('is_overdue', False)
                t_is_done = t.get('is_done', False)
                overdue_str = "Yes" if t_is_overdue else "No"

                row_values = [
                    (t_id, align_center, font_data_bold, row_fill),
                    (t_name, align_left, font_data, row_fill),
                    (t_dept, align_left, font_data, row_fill),
                    (t_tag, align_left, font_data, row_fill),
                    (t_proj, align_left, font_data, row_fill),
                    (t_created_on, align_center, font_data, row_fill),
                    (t_created_by, align_left, font_data, row_fill),
                    (t_assignees, align_left, font_data, row_fill),
                    (t_prog_str, align_center, font_done if t_is_done else font_data_bold, fill_done if t_is_done else row_fill),
                    (t_days_open, align_center, font_data, row_fill),
                    (t_deadline, align_center, font_data, row_fill),
                    (t_stage, align_center, font_data, row_fill),
                    (t_priority, align_center, font_high_prio if prio_int >= 2 else font_data, fill_high_prio if prio_int >= 2 else row_fill),
                    (t_subtasks, align_center, font_data, row_fill),
                    (overdue_str, align_center, font_overdue if t_is_overdue else font_data, fill_overdue if t_is_overdue else row_fill),
                ]

                for col_idx, (val, align, font, fill) in enumerate(row_values, start=1):
                    cell = ws.cell(row=current_row, column=col_idx, value=val)
                    cell.alignment = align
                    cell.font = font
                    cell.fill = fill
                    cell.border = border_data

                current_row += 1

            # 6. Total / Summary Row (or Empty Message)
            if not all_tasks:
                ws.row_dimensions[current_row].height = 28
                ws.merge_cells(start_row=current_row, start_column=1, end_row=current_row, end_column=15)
                empty_cell = ws.cell(row=current_row, column=1, value="No tasks found matching the applied filters.")
                empty_cell.font = Font(name="Calibri", size=11, italic=True, color="64748B")
                empty_cell.alignment = align_center
                for c in range(1, 16):
                    ws.cell(row=current_row, column=c).border = border_data
            else:
                ws.row_dimensions[current_row].height = 24
                avg_prog = int(round(total_progress_sum / len(all_tasks)))
                summary_fill = PatternFill(start_color="E2E8F0", end_color="E2E8F0", fill_type="solid")
                font_summary = Font(name="Calibri", size=10, bold=True, color="0F172A")

                # Merge A to H for "Total: N Tasks"
                ws.merge_cells(start_row=current_row, start_column=1, end_row=current_row, end_column=8)
                sum_cell = ws.cell(row=current_row, column=1, value=f"Total: {len(all_tasks)} Tasks")
                sum_cell.font = font_summary
                sum_cell.fill = summary_fill
                sum_cell.alignment = Alignment(horizontal="right", vertical="center", indent=1)

                for c in range(1, 9):
                    ws.cell(row=current_row, column=c).fill = summary_fill
                    ws.cell(row=current_row, column=c).border = border_data

                # Average progress cell (Col 9)
                prog_sum_cell = ws.cell(row=current_row, column=9, value=f"{avg_prog}% (Avg)")
                prog_sum_cell.font = font_summary
                prog_sum_cell.fill = summary_fill
                prog_sum_cell.alignment = align_center
                prog_sum_cell.border = border_data

                for c in range(10, 16):
                    empty_sum_cell = ws.cell(row=current_row, column=c, value="")
                    empty_sum_cell.fill = summary_fill
                    empty_sum_cell.border = border_data

                # Auto-Filter on header
                last_data_row = current_row - 1
                ws.auto_filter.ref = f"A{header_row}:O{last_data_row}"

            # Freeze Panes
            ws.freeze_panes = f"A{header_row + 1}"

            output = io.BytesIO()
            wb.save(output)
            output.seek(0)

            date_slug = fields.Date.today().strftime('%Y%m%d')
            time_slug = datetime.now().strftime('%H%M%S')
            filename = f"Tasks_Report_{date_slug}_{time_slug}.xlsx"

            headers_resp = [
                ('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'),
                ('Content-Disposition', f'attachment; filename="{filename}"'),
                ('Cache-Control', 'no-cache, no-store, must-revalidate'),
            ]
            return request.make_response(output.getvalue(), headers=headers_resp)

        except Exception as e:
            _logger.exception("Failed to export tasks to Excel: %s", e)
            return request.make_response(
                f"Error generating tasks report: {str(e)}",
                headers=[('Content-Type', 'text/plain')],
                status=500
            )
